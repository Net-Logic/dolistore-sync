import { Lexer } from 'marked'
import { FEATURES_HEADINGS, GENERATED_HEADING_STEMS, HOW_HEADINGS } from './i18n.mjs'

// No case, no accents, single spaces, no trailing colon or dot
export function normalizeHeading(text) {
  return String(text ?? '')
    .normalize('NFD').replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/[\s ]+/g, ' ')
    .replace(/[\s:.!?]+$/, '')
    .trim()
}

// The module name is the part of the title before " - "
export function moduleName(title) {
  return String(title ?? '').split(' - ')[0].trim()
}

const matches = (table, lang, heading) => [...(table[lang] || []), ...table.en].includes(heading)

function classifyHeading(text, lang) {
  const heading = normalizeHeading(text)
  if (matches(FEATURES_HEADINGS, lang, heading)) {
    return 'features'
  }
  if (matches(HOW_HEADINGS, lang, heading)) {
    return 'how'
  }
  if (GENERATED_HEADING_STEMS.some((stem) => heading.startsWith(stem))) {
    return 'generated'
  }
  return 'unknown'
}

// "**Lead**: text", "**Lead** - text", "**Lead:** text" (also __Lead__)
function splitFeature(item) {
  const match = item.text.trim().match(/^(\*\*|__)([\s\S]+?)\1([\s\S]*)$/)
  if (!match) {
    return null
  }
  return {
    lead: match[2].trim().replace(/\s*:$/, ''),
    text: match[3].replace(/^\s*[:\-–—]\s*/, '').trim(),
  }
}

const hasNestedBlock = (item) => item.tokens.some((t) => t.type === 'list' || t.type === 'code' || t.type === 'blockquote')

// Body of a module file in the "netlogic" layout: intro paragraphs, ## Features (bullet list with
// bold lead-ins), optional ## How it works (numbered list), nothing else.
// Returns the parts and the problems found (messages without the file name).
export function parseLayoutBody(markdown, lang) {
  const result = { intro: [], introBold: [], features: [], featureCount: 0, how: null, errors: [] }
  const errors = result.errors
  let section = 'intro'
  let seenFeatures = false
  let featuresList = false
  let introTokens = null
  for (const token of Lexer.lex(String(markdown ?? ''), { gfm: true })) {
    if (token.type === 'space') {
      continue
    }
    if (token.type === 'heading') {
      if (token.depth !== 2) {
        errors.push(`only ## headings are allowed, got "${token.text}"`)
        section = 'skip'
        continue
      }
      const kind = classifyHeading(token.text, lang)
      if (kind === 'generated') {
        errors.push(`remove the hand-written "${token.text}" section: it is generated by the layout`)
        section = 'skip'
      } else if (kind === 'unknown') {
        errors.push(`unexpected section "${token.text}": only the intro, Features and How it works are written by hand`)
        section = 'skip'
      } else if (kind === 'features') {
        if (seenFeatures) {
          errors.push('the Features section is written twice')
        }
        if (result.how !== null) {
          errors.push('the Features section must come before How it works')
        }
        seenFeatures = true
        section = 'features'
      } else {
        if (result.how !== null) {
          errors.push('the How it works section is written twice')
        }
        result.how = []
        section = 'how'
      }
      continue
    }
    if (section === 'intro') {
      if (token.type === 'paragraph') {
        result.intro.push(token.text)
        introTokens ??= token.tokens
      } else {
        errors.push(`the intro must be paragraphs only, got a ${token.type}`)
      }
    } else if (section === 'features') {
      if (token.type !== 'list' || token.ordered || featuresList) {
        errors.push('Features: only one bullet list is allowed after the heading')
        continue
      }
      featuresList = true
      result.featureCount = token.items.length
      token.items.forEach((item, i) => {
        const feature = splitFeature(item)
        if (hasNestedBlock(item)) {
          errors.push(`feature ${i + 1} must be a single item (no nested list or block)`)
        } else if (!feature) {
          errors.push(`feature ${i + 1} must start with a bold lead-in (**...**)`)
        } else if (feature.text === '') {
          errors.push(`feature ${i + 1} "${feature.lead}" has no text after its bold lead-in`)
        } else {
          result.features.push(feature)
        }
      })
    } else if (section === 'how') {
      if (token.type !== 'list' || !token.ordered || result.how.length > 0) {
        errors.push('How it works: only one numbered list is allowed after the heading')
        continue
      }
      for (const item of token.items) {
        result.how.push(item.text.trim())
      }
    }
  }
  if (result.intro.length === 0) {
    errors.push('the body must start with an intro paragraph')
  } else if (result.intro.length > 2) {
    errors.push(`the intro must be 1 or 2 paragraphs, got ${result.intro.length}`)
  }
  result.introBold = (introTokens || []).filter((t) => t.type === 'strong').map((t) => t.text)
  if (!seenFeatures) {
    errors.push('the Features section is missing (## heading then a bullet list)')
  } else if (!featuresList) {
    errors.push('Features: a bullet list is required after the heading')
  }
  if (result.how !== null && result.how.length === 0) {
    errors.push('How it works: a numbered list is required after the heading')
  }
  return result
}
