import { readFileSync } from 'node:fs'
import { isImageBody } from '../checks.mjs'
import { escapeHtml } from '../markdown.mjs'

// The Net Logic banner at the top of every description of the netlogic layout, served by jsDelivr from
// this repository. The ref is the tag where the image first shipped, NOT the version of the tool:
// later releases keep pointing to v0.5.0 until the image itself changes. To change the image, commit
// it under a new file name (or replace it and ship a new tag), then point this URL to that file and tag.
export const BANNER_URL = 'https://cdn.jsdelivr.net/gh/Net-Logic/dolistore-sync@v0.5.0/assets/netlogic-banner.png'
// The same image in this repository: the preview embeds it, so it shows offline
export const BANNER_FILE = new URL('../../assets/netlogic-banner.png', import.meta.url)
export const BANNER_LINK = 'https://www.netlogic.fr'
export const BANNER_ALT = 'Net Logic - Dolibarr Preferred Partner'
export const BANNER_WIDTH = 675
export const BANNER_HEIGHT = 130

// The banner markup, generated by the tool only (constants, no module text). The preview swaps
// BANNER_URL for the embedded image afterwards; what is sent to DoliStore always holds BANNER_URL.
export function bannerImage() {
  return `<a href="${escapeHtml(BANNER_LINK)}"><img src="${escapeHtml(BANNER_URL)}" alt="${escapeHtml(BANNER_ALT)}" width="${BANNER_WIDTH}" height="${BANNER_HEIGHT}"></a>`
}

// data: URI of the local image, for the preview
export function bannerDataUri() {
  return `data:image/png;base64,${readFileSync(BANNER_FILE).toString('base64')}`
}

async function fetchImage(url) {
  const response = await fetch(url, { redirect: 'follow', signal: AbortSignal.timeout(30000) })
  return { status: response.status, contentType: response.headers.get('content-type') ?? '', body: Buffer.from(await response.arrayBuffer()) }
}

// null when BANNER_URL serves an image (HTTP 200, image/* content type, image bytes), else what is wrong
export async function checkBannerImage({ url = BANNER_URL, fetch: get = fetchImage } = {}) {
  let response
  try {
    response = await get(url)
  } catch (error) {
    return `could not fetch it: ${error.message}`
  }
  if (response.status !== 200) {
    return `HTTP ${response.status}`
  }
  const type = String(response.contentType ?? '').trim()
  if (!type.toLowerCase().startsWith('image/')) {
    return `not an image (content type ${type || 'none'})`
  }
  if (!isImageBody(type, response.body)) {
    return `not an image (content type ${type}, but the body is no PNG, JPEG, GIF or WebP)`
  }
  return null
}

// Before a run with the netlogic layout, ahead of the login: the description shows BANNER_URL, so a
// missing image would be a broken image on the public page. A real submit is refused (thrown, nothing
// is touched on DoliStore); a dry run gets the message back, to report it as an error once it is done.
export async function bannerPreflight({ layout, dryRun, fetch: get } = {}) {
  if (layout !== 'netlogic') {
    return null
  }
  const problem = await checkBannerImage({ fetch: get })
  if (problem === null) {
    return null
  }
  const message = `the Net Logic banner image of the layout is not available at ${BANNER_URL} (${problem}): publish the tag that ships assets/netlogic-banner.png, or fix BANNER_URL in src/layout/banner.mjs`
  if (!dryRun) {
    throw new Error(`Real submit refused: ${message}`)
  }
  return message
}
